<?php
if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Merges raw ranges into a sorted, non-overlapping list and writes it out
 * as a plain PHP data file the mu-plugin can include with no DB dependency.
 */
class WPOpsec_IP_Blocklist_Compiler {

	/**
	 * Private/reserved IPv4 space (RFC 1918 + IANA special-purpose registry).
	 * REMOTE_ADDR can't be spoofed over TCP, so a "bogon" source address only
	 * ever means a LAN/dev/VPN client or a reverse proxy passing an internal
	 * hop IP — never an attacker. Some sources (e.g. FireHOL's fullbogons
	 * component) list these as "bad" anyway; always excluded here regardless
	 * of source, since blocking them has no security value and guarantees
	 * self-lockout on any non-public deployment.
	 */
	const RESERVED_CIDRS = array(
		'0.0.0.0/8',
		'10.0.0.0/8',
		'100.64.0.0/10',
		'127.0.0.0/8',
		'169.254.0.0/16',
		'172.16.0.0/12',
		'192.0.0.0/24',
		'192.0.2.0/24',
		'192.88.99.0/24',
		'192.168.0.0/16',
		'198.18.0.0/15',
		'198.51.100.0/24',
		'203.0.113.0/24',
		'224.0.0.0/4',
		'240.0.0.0/4',
	);

	public static function data_file() {
		return WPOPSEC_CHECKS_DIR . '/data/ip-blocklist-ranges.php';
	}

	/**
	 * @param array<int, array{0:int,1:int,2:string}> $ranges
	 * @return array{count_raw:int, count_merged:int, by_source:array<string,int>}
	 */
	public static function compile( array $ranges ) {
		$by_source = array();
		foreach ( $ranges as $r ) {
			$src               = $r[2] ?? 'unknown';
			$by_source[ $src ] = ( $by_source[ $src ] ?? 0 ) + 1;
		}

		$merged = self::merge( $ranges );
		$merged = self::exclude_reserved( $merged );
		self::write( $merged );

		return array(
			'count_raw'    => count( $ranges ),
			'count_merged' => count( $merged ),
			'by_source'    => $by_source,
		);
	}

	/** @return array<int, array{0:int,1:int}> sorted, non-overlapping */
	private static function merge( array $ranges ) {
		if ( empty( $ranges ) ) {
			return array();
		}

		usort(
			$ranges,
			function ( $a, $b ) {
				return $a[0] <=> $b[0];
			}
		);

		$merged  = array();
		$current = array( $ranges[0][0], $ranges[0][1] );

		for ( $i = 1, $n = count( $ranges ); $i < $n; $i++ ) {
			list( $start, $end ) = $ranges[ $i ];

			if ( $start <= $current[1] + 1 ) {
				$current[1] = max( $current[1], $end );
			} else {
				$merged[] = $current;
				$current  = array( $start, $end );
			}
		}
		$merged[] = $current;

		return $merged;
	}

	/** @return array<int, array{0:int,1:int}> $merged with reserved ranges cut out */
	private static function exclude_reserved( array $merged ) {
		$reserved = array_map( array( __CLASS__, 'cidr_to_range' ), self::RESERVED_CIDRS );

		foreach ( $reserved as $r ) {
			$next = array();
			foreach ( $merged as $piece ) {
				if ( $piece[1] < $r[0] || $piece[0] > $r[1] ) {
					$next[] = $piece; // no overlap
					continue;
				}
				if ( $piece[0] < $r[0] ) {
					$next[] = array( $piece[0], $r[0] - 1 ); // keep the part before
				}
				if ( $piece[1] > $r[1] ) {
					$next[] = array( $r[1] + 1, $piece[1] ); // keep the part after
				}
			}
			$merged = $next;
		}

		return $merged;
	}

	private static function cidr_to_range( $cidr ) {
		list( $ip, $prefix ) = explode( '/', $cidr );
		$mask  = ( 0xFFFFFFFF << ( 32 - (int) $prefix ) ) & 0xFFFFFFFF;
		$start = ip2long( $ip ) & $mask;
		return array( $start, $start | ( ~$mask & 0xFFFFFFFF ) );
	}

	private static function write( array $merged ) {
		$dir = dirname( self::data_file() );
		if ( ! file_exists( $dir ) ) {
			wp_mkdir_p( $dir );
		}

		$export = "<?php\n// Auto-generated by wp-opsec ip-blocklist module. Do not edit.\nreturn " . var_export( $merged, true ) . ";\n";

		$tmp = self::data_file() . '.tmp-' . wp_generate_password( 8, false );
		file_put_contents( $tmp, $export, LOCK_EX );
		rename( $tmp, self::data_file() );

		// opcache.revalidate_freq means a rewritten file can serve stale
		// bytecode for a few seconds otherwise — force it, since this file
		// is rewritten in place by cron and must take effect immediately.
		if ( function_exists( 'opcache_invalidate' ) ) {
			opcache_invalidate( self::data_file(), true );
		}
	}
}
